#!/usr/bin/env python3
"""Copies the BS calendar table from NepaliDateConverter.kt into docs/bs.js for the website.

Run after changing the table:  python3 scripts/gen-site-calendar.py
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
kotlin = (root / "app/src/main/java/com/kushal/xdate/NepaliDateConverter.kt").read_text(encoding="utf-8")

rows = re.findall(r"(\d{4}) to intArrayOf\(([\d,\s]+)\)", kotlin)
years = [int(y) for y, _ in rows]
assert years == list(range(years[0], years[0] + len(years))), "years must be consecutive"
days = [[int(d) for d in row.split(",")] for _, row in rows]
verified = int(re.search(r"VERIFIED_UNTIL_YEAR = (\d+)", kotlin).group(1))


def strings(name):
    block = re.search(name + r" = arrayOf\((.*?)\)", kotlin, re.S).group(1)
    return re.findall(r'"([^"]+)"', block)


data = {
    "firstYear": years[0],
    "verifiedUntil": verified,
    "months": strings("nepaliMonths"),
    "monthsEn": strings("nepaliMonthsEn"),
    "weekdays": strings("nepaliDayNames"),
    "days": days,
}
out = root / "docs/bs.js"
out.write_text(
    "// Generated by scripts/gen-site-calendar.py from NepaliDateConverter.kt. Do not edit.\n"
    "window.BS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"wrote {out.relative_to(root)}: BS {years[0]}-{years[-1]}")
